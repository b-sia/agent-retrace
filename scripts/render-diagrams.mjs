/**
 * Renders every Mermaid source in docs/diagrams/*.mmd to an SVG next to it.
 *
 * The docs embed the SVGs rather than ```mermaid blocks, because editor
 * previews and npm's package page do not render Mermaid. After editing a
 * .mmd file, run this and commit both files:
 *
 *   npm run docs:diagrams
 *
 * Each SVG starts with a comment holding a hash of everything that shaped it:
 * its source, the shared config and the renderer versions from the lockfile.
 * `--check` (npm run docs:diagrams:check, part of CI) recomputes the hashes
 * without rendering, so it needs no browser, and fails when an SVG is
 * missing, stale or has no source.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "docs", "diagrams");
const configPath = join(dir, "mermaid.config.json");
const STAMP =
  /^<!-- Generated by scripts\/render-diagrams\.mjs from (\S+), sha256:([0-9a-f]{64})\. -->\n/;

/**
 * Reads the installed version of a package.
 *
 * @param {string} name - Package name.
 * @returns {string} Its version, as resolved by the lockfile.
 */
function installedVersion(name) {
  const manifest = JSON.parse(
    readFileSync(join(root, "node_modules", name, "package.json"), "utf8"),
  );
  return manifest.version;
}

/**
 * Hashes everything that determines how a diagram renders.
 *
 * @param {string} source - Contents of the .mmd file.
 * @returns {string} Hex SHA-256 digest.
 */
function inputHash(source) {
  return createHash("sha256")
    .update(source)
    .update("\0")
    .update(readFileSync(configPath, "utf8"))
    .update("\0")
    .update(`@mermaid-js/mermaid-cli@${installedVersion("@mermaid-js/mermaid-cli")}`)
    .update(`mermaid@${installedVersion("mermaid")}`)
    .digest("hex");
}

/**
 * Builds the comment that opens a generated SVG.
 *
 * @param {string} name - File name of the .mmd source.
 * @param {string} hash - Its input hash.
 * @returns {string} The comment line.
 */
function stamp(name, hash) {
  return `<!-- Generated by scripts/render-diagrams.mjs from ${name}, sha256:${hash}. -->\n`;
}

/**
 * Lists the diagram sources.
 *
 * @returns {string[]} .mmd file names in docs/diagrams, sorted.
 */
function sources() {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".mmd"))
    .sort();
}

/**
 * Gives an SVG its natural pixel size. Mermaid writes `width="100%"`, which
 * makes an `<img>` stretch a small diagram to the full page width, blowing
 * its text up; explicit sizes let it show at 1:1 and only shrink to fit.
 *
 * @param {string} svg - SVG markup as Mermaid wrote it.
 * @returns {string} The markup with `width` and `height` set from its viewBox.
 * @throws {Error} When the root element has no viewBox or no `width="100%"`.
 */
function fixSize(svg) {
  const root = /<svg\b[^>]*>/.exec(svg)?.[0] ?? "";
  const viewBox = /viewBox="[-\d.]+ [-\d.]+ ([\d.]+) ([\d.]+)"/.exec(root);
  if (!viewBox || !root.includes(' width="100%"')) {
    throw new Error(`unexpected <svg> root element from Mermaid: ${root.slice(0, 200)}`);
  }
  const [width, height] = [viewBox[1], viewBox[2]].map((n) => Math.ceil(Number(n)));
  return svg.replace(root, root.replace(' width="100%"', ` width="${width}" height="${height}"`));
}

/**
 * Renders every diagram to SVG and stamps it.
 *
 * @returns {Promise<void>}
 * @throws {Error} When Mermaid fails, e.g. on a syntax error.
 */
async function renderAll() {
  const { run } = await import("@mermaid-js/mermaid-cli");
  const mermaidConfig = JSON.parse(readFileSync(configPath, "utf8"));
  for (const name of sources()) {
    const input = join(dir, name);
    const output = input.replace(/\.mmd$/, ".svg");
    await run(input, output, {
      quiet: true,
      // Only our own committed sources are rendered, and Chrome's sandbox is
      // unavailable on some Linux setups (containers, Ubuntu's AppArmor).
      puppeteerConfig: { args: ["--no-sandbox"] },
      parseMMDOptions: { mermaidConfig, backgroundColor: "white" },
    });
    const svg = fixSize(readFileSync(output, "utf8"));
    writeFileSync(output, stamp(name, inputHash(readFileSync(input, "utf8"))) + svg);
    console.log(`rendered docs/diagrams/${name.replace(/\.mmd$/, ".svg")}`);
  }
}

/**
 * Verifies that every SVG was rendered from its current source.
 *
 * @returns {string[]} One message per problem; empty when all are up to date.
 */
function checkAll() {
  const problems = [];
  const names = sources();
  for (const name of names) {
    const svgName = name.replace(/\.mmd$/, ".svg");
    let svg;
    try {
      svg = readFileSync(join(dir, svgName), "utf8");
    } catch {
      problems.push(`docs/diagrams/${svgName} is missing`);
      continue;
    }
    const match = STAMP.exec(svg);
    if (
      !match ||
      match[1] !== name ||
      match[2] !== inputHash(readFileSync(join(dir, name), "utf8"))
    ) {
      problems.push(`docs/diagrams/${svgName} is out of date with ${name}`);
    }
  }
  for (const svgName of readdirSync(dir).filter((f) => f.endsWith(".svg"))) {
    if (!names.includes(svgName.replace(/\.svg$/, ".mmd"))) {
      problems.push(`docs/diagrams/${svgName} has no .mmd source`);
    }
  }
  return problems;
}

if (process.argv.includes("--check")) {
  const problems = checkAll();
  if (problems.length > 0) {
    for (const p of problems) console.error(p);
    console.error("Run `npm run docs:diagrams` and commit the result.");
    process.exit(1);
  }
  console.log("docs/diagrams: all SVGs are up to date");
} else {
  await renderAll();
}
